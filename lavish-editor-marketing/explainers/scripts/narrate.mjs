#!/usr/bin/env node
// Turn an explainer's beats.json into measured narration audio, then write the
// measured timings into its index.html so scenes and voice share one clock.
//
//   node narrate.mjs <explainer-dir>           synthesize every beat, rewrite the timing block
//   node narrate.mjs <explainer-dir> --check   verify committed audio and timings, no synthesis
//
// HyperFrames owns the voice (its local Kokoro model) and the MP4 render, so this
// script only measures durations and keeps the composition in sync with them.

import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HYPERFRAMES = "hyperframes@0.5.7";
// Every number below is part of the recipe, not a style choice: the lead-in lets the
// first beat settle, the gap separates two narrations, the tail lets the last frame read.
const LEAD_IN_SECONDS = 0.5;
const GAP_SECONDS = 0.35;
const TAIL_SECONDS = 1.4;
const DURATION_TOLERANCE_SECONDS = 0.05;
const BLOCK_START = "<!-- narrate:start";
const BLOCK_END = "<!-- narrate:end -->";

function round(value) {
  return Math.round(value * 100) / 100;
}

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function probeSeconds(path) {
  const output = execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path], {
    encoding: "utf8",
  });
  const seconds = Number.parseFloat(output.trim());
  if (!Number.isFinite(seconds)) throw new Error(`ffprobe could not read a duration from ${path}`);
  return seconds;
}

// A WAV header states its own sample rate and byte rate, so the check needs no
// ffmpeg install and behaves the same on every CI runner. Anything else falls back
// to ffprobe, which ships with the ffmpeg the renderer already requires.
function audioSeconds(path) {
  if (path.endsWith(".wav")) {
    const buffer = readFileSync(path);
    if (buffer.length > 44 && buffer.toString("ascii", 0, 4) === "RIFF" && buffer.toString("ascii", 8, 12) === "WAVE") {
      let offset = 12;
      let byteRate = 0;
      while (offset + 8 <= buffer.length) {
        const id = buffer.toString("ascii", offset, offset + 4);
        const size = buffer.readUInt32LE(offset + 4);
        if (id === "fmt " && offset + 20 <= buffer.length) byteRate = buffer.readUInt32LE(offset + 16);
        if (id === "data" && byteRate > 0) return size / byteRate;
        offset += 8 + size + (size % 2);
      }
    }
  }
  return probeSeconds(path);
}

function narrationFile(index, id) {
  return `assets/narration/${String(index + 1).padStart(2, "0")}-${id}.wav`;
}

function synthesize(beatsPath, dir) {
  const beats = readJson(beatsPath);
  const voice = beats.voice || "am_michael";
  const speed = beats.speed || 1;
  const narration = {
    generated_by: "lavish-editor-marketing/explainers/scripts/narrate.mjs",
    voice,
    speed,
    lead_in_seconds: LEAD_IN_SECONDS,
    total_seconds: 0,
    beats: [],
  };
  let cursor = LEAD_IN_SECONDS;
  beats.beats.forEach((beat, index) => {
    const file = narrationFile(index, beat.id);
    const output = join(dir, file);
    mkdirSync(dirname(output), { recursive: true });
    execFileSync("npx", ["--yes", HYPERFRAMES, "tts", beat.narration, "-o", output, "-v", voice, "-s", String(speed)], {
      stdio: ["ignore", "pipe", "inherit"],
    });
    const seconds = round(audioSeconds(output));
    const start = round(cursor);
    narration.beats.push({ id: beat.id, file, seconds, start, end: round(start + seconds) });
    cursor = start + seconds + GAP_SECONDS;
    process.stdout.write(`narrated ${beat.id}: ${seconds.toFixed(2)}s starting ${start.toFixed(2)}s\n`);
  });
  narration.total_seconds = round(cursor - GAP_SECONDS + TAIL_SECONDS);
  return narration;
}

function timingBlock(narration) {
  const lines = [
    `      ${BLOCK_START} (generated by ../scripts/narrate.mjs from beats.json) -->`,
    `      <script id="narration-data" type="application/json">`,
    JSON.stringify(narration, null, 2)
      .split("\n")
      .map((line) => `        ${line}`)
      .join("\n"),
    "      </script>",
  ];
  for (const beat of narration.beats) {
    lines.push(
      `      <audio id="narration-${beat.id}" src="${beat.file}" data-start="${beat.start}" data-duration="${beat.seconds}" data-track-index="1"></audio>`,
    );
  }
  lines.push(`      ${BLOCK_END}`);
  return lines.join("\n");
}

function replaceBlock(html, block) {
  const start = html.indexOf(`<!-- narrate:start`);
  const end = html.indexOf(BLOCK_END);
  if (start === -1 || end === -1 || end < start) {
    throw new Error("index.html is missing its <!-- narrate:start --> / <!-- narrate:end --> markers");
  }
  const before = html.slice(0, html.lastIndexOf("\n", start) + 1);
  const after = html.slice(end + BLOCK_END.length);
  return `${before}${block}${after}`;
}

function setTotalDuration(html, total) {
  const root = /<div[^>]*id="root"[^>]*>/.exec(html);
  if (!root) throw new Error('index.html is missing the <div id="root"> composition element');
  if (!/data-duration="[^"]*"/.test(root[0])) {
    throw new Error("the #root composition element needs a data-duration attribute");
  }
  const tag = root[0].replace(/data-duration="[^"]*"/, `data-duration="${total}"`);
  return html.replace(root[0], tag);
}

export function applyTiming(html, narration) {
  return setTotalDuration(replaceBlock(html, timingBlock(narration)), narration.total_seconds);
}

export function compareTiming(html, narration) {
  const problems = [];
  const start = html.indexOf(BLOCK_START);
  const end = html.indexOf(BLOCK_END);
  if (start === -1 || end === -1)
    return ["index.html is missing its <!-- narrate:start --> / <!-- narrate:end --> markers"];
  const block = html.slice(start, end);
  const json = /<script id="narration-data" type="application\/json">([\s\S]*?)<\/script>/.exec(block);
  if (!json) {
    problems.push("index.html has no narration-data block; run narrate.mjs to write one");
  } else {
    const embedded = JSON.parse(json[1].trim());
    if (JSON.stringify(embedded) !== JSON.stringify(narration)) {
      problems.push("index.html narration-data does not match narration.json");
    }
  }
  const audio = [...block.matchAll(/<audio\b[^>]*>/g)].map((match) => match[0]);
  if (audio.length !== narration.beats.length) {
    problems.push(`index.html lists ${audio.length} narration clips, narration.json has ${narration.beats.length}`);
  }
  narration.beats.forEach((beat) => {
    const tag = audio.find((candidate) => candidate.includes(`id="narration-${beat.id}"`));
    if (!tag) {
      problems.push(`index.html has no <audio id="narration-${beat.id}">`);
      return;
    }
    for (const attribute of ["data-start", "data-duration"]) {
      const expected = attribute === "data-start" ? beat.start : beat.seconds;
      const found = new RegExp(`${attribute}="([^"]*)"`).exec(tag);
      if (!found || Number(found[1]) !== expected) {
        problems.push(`<audio id="narration-${beat.id}"> needs ${attribute}="${expected}"`);
      }
    }
  });
  const root = /<div[^>]*id="root"[^>]*>/.exec(html);
  const rootDuration = root && /data-duration="([^"]*)"/.exec(root[0]);
  if (!rootDuration || Number(rootDuration[1]) !== narration.total_seconds) {
    problems.push(`#root needs data-duration="${narration.total_seconds}"`);
  }
  return problems;
}

export function checkExplainer(dir) {
  const beats = readJson(join(dir, "beats.json"));
  const narration = readJson(join(dir, "narration.json"));
  const html = readFileSync(join(dir, "index.html"), "utf8");
  const problems = compareTiming(html, narration);
  const ids = beats.beats.map((beat) => beat.id);
  const narratedIds = narration.beats.map((beat) => beat.id);
  if (ids.join() !== narratedIds.join()) {
    problems.push(`narration.json beats [${narratedIds}] do not follow beats.json [${ids}]`);
  }
  if (narration.voice !== (beats.voice || "am_michael")) {
    problems.push(`narration.json voice ${narration.voice} does not match beats.json ${beats.voice}`);
  }
  for (const id of ids) {
    if (!html.includes(`id="beat-${id}"`)) problems.push(`index.html has no scene id="beat-${id}"`);
  }
  for (const beat of narration.beats) {
    const file = join(dir, beat.file);
    if (!existsSync(file)) {
      problems.push(`missing narration audio ${beat.file}`);
      continue;
    }
    const measured = audioSeconds(file);
    if (Math.abs(measured - beat.seconds) > DURATION_TOLERANCE_SECONDS) {
      problems.push(
        `${beat.file} runs ${measured.toFixed(2)}s but narration.json records ${beat.seconds}s; re-run narrate.mjs`,
      );
    }
  }
  return problems;
}

function main(argv) {
  const check = argv.includes("--check");
  const dir = resolve(argv.find((arg) => !arg.startsWith("-")) || ".");
  const beatsPath = join(dir, "beats.json");
  if (!existsSync(beatsPath)) throw new Error(`no beats.json in ${dir}`);
  if (check) {
    const problems = checkExplainer(dir);
    if (problems.length) {
      process.stderr.write(`narration check failed for ${dir}\n${problems.map((p) => `  - ${p}`).join("\n")}\n`);
      process.exitCode = 1;
      return;
    }
    process.stdout.write(`narration check passed for ${dir}\n`);
    return;
  }
  const narration = synthesize(beatsPath, dir);
  writeFileSync(join(dir, "narration.json"), `${JSON.stringify(narration, null, 2)}\n`);
  const index = join(dir, "index.html");
  writeFileSync(index, applyTiming(readFileSync(index, "utf8"), narration));
  const problems = checkExplainer(dir);
  if (problems.length) {
    process.stderr.write(
      `narration written but the explainer is inconsistent\n${problems.map((p) => `  - ${p}`).join("\n")}\n`,
    );
    process.exitCode = 1;
    return;
  }
  process.stdout.write(`wrote narration.json and the timing block in ${index} (${narration.total_seconds}s)\n`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  main(process.argv.slice(2));
}
